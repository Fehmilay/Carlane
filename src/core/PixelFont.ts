const LOWER_MAP: Record<string, string> = { 'ä': 'Ä', 'ö': 'Ö', 'ü': 'Ü', 'é': 'É', 'ç': 'Ç', 'ğ': 'Ğ', 'ı': 'I', 'ş': 'Ş', 'á': 'Á', 'í': 'Í', 'ó': 'Ó', 'ú': 'Ú', 'ñ': 'Ñ', 'å': 'Å', 'æ': 'Æ', 'ø': 'Ø', 'ð': 'Ð', 'þ': 'Þ', 'ł': 'Ł', 'č': 'Č', 'è': 'É', 'ê': 'É', 'à': 'Á', 'â': 'Á', 'ô': 'Ó', 'û': 'Ú', 'ý': 'Y' };

export class PixelFont {
  readonly gw = 5;
  readonly gh = 7;
  private glyphCache = new Map<string, HTMLCanvasElement>();

  private glyph(ch: string, color: string): HTMLCanvasElement | null {
    let c = ch.toUpperCase();
    if (LOWER_MAP[ch]) c = LOWER_MAP[ch];
    const rows = G[c] ?? G['?'];
    const key = c + color;
    const hit = this.glyphCache.get(key);
    if (hit) return hit;
    const cv = document.createElement('canvas');
    cv.width = this.gw; cv.height = this.gh;
    const x = cv.getContext('2d')!;
    x.fillStyle = color;
    for (let j = 0; j < this.gh; j++) for (let i = 0; i < this.gw; i++) if (rows[j][i] === '#') x.fillRect(i, j, 1, 1);
    this.glyphCache.set(key, cv);
    return cv;
  }

  measure(str: string, o: TextOpts = {}): number {
    const s = o.scale ?? 1;
    const sp = (o.spacing ?? 1) * s;
    const chars = Array.from(str);
    if (!chars.length) return 0;
    return chars.length * this.gw * s + (chars.length - 1) * sp;
  }

  private wrapLines(str: string, o: TextOpts): string[] {
    if (!o.wrap) return str.split('\n');
    const out: string[] = [];
    for (const para of str.split('\n')) {
      const words = para.split(' ');
      let line = '';
      for (const w of words) {
        const cand = line ? line + ' ' + w : w;
        if (this.measure(cand, o) > o.wrap && line) { out.push(line); line = w; } else line = cand;
      }
      out.push(line);
    }
    return out;
  }

  /** Draws text, returns total height drawn. */
  draw(ctx: CanvasRenderingContext2D, str: string, x: number, y: number, o: TextOpts = {}): number {
    const s = Math.max(1, Math.round(o.scale ?? 1));
    const color = o.color ?? '#f4f4f0';
    const sp = (o.spacing ?? 1) * s;
    const lh = o.lineHeight ?? (this.gh + 2) * s;
    const lines = this.wrapLines(str, o);
    if (o.alpha !== undefined) ctx.globalAlpha = o.alpha;
    ctx.imageSmoothingEnabled = false;
    lines.forEach((line, li) => {
      const chars = Array.from(line);
      const width = this.measure(line, o);
      let cx = Math.round(x);
      if (o.align === 'center') cx = Math.round(x - width / 2);
      else if (o.align === 'right') cx = Math.round(x - width);
      const cy = Math.round(y + li * lh);
      const pass = (col: string, dx: number, dy: number) => {
        let px = cx;
        for (let i = 0; i < chars.length; i++) {
          const ch = chars[i];
          const wob = o.wave ? Math.round(Math.sin((o.t ?? 0) * 6 + i * 0.7) * o.wave) : 0;
          const g = this.glyph(ch, col);
          if (g) ctx.drawImage(g, 0, 0, this.gw, this.gh, px + dx, cy + dy + wob, this.gw * s, this.gh * s);
          px += this.gw * s + sp;
        }
      };
      if (o.outline) {
        for (let dy = -s; dy <= s; dy += s) for (let dx = -s; dx <= s; dx += s) if (dx || dy) pass(o.outline, dx, dy);
      }
      if (o.shadow) pass(o.shadow, s, s);
      pass(color, 0, 0);
    });
    if (o.alpha !== undefined) ctx.globalAlpha = 1;
    return lines.length * lh;
  }
}
