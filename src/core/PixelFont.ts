// 5×7 bitmap font (A–Z, 0–9, punctuation, German umlauts) + a chunky 8×8 "title" font
// derived by scaling. Every glyph is 5 columns × 7 rows, '#' = pixel.
export interface TextOpts {
  color?: string;
  /** integer scale */
  scale?: number;
  align?: 'left' | 'center' | 'right';
  /** outline / shadow color */
  shadow?: string;
  outline?: string;
  /** letter spacing in px (default 1) */
  spacing?: number;
  /** wave animation amplitude / time (used by title screens) */
  wave?: number;
  t?: number;
  alpha?: number;
  /** max width for word-wrap (game px); returns height when wrapping */
  wrap?: number;
  lineHeight?: number;
}

